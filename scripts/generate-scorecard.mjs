/**
 * FOUNDATION F7 — generates `docs/SCORECARD.md`.
 *
 *   node scripts/generate-scorecard.mjs           # write the scorecard
 *   node scripts/generate-scorecard.mjs --check   # fail if it is stale
 *
 * WHY A GENERATOR AND NOT A HAND-WRITTEN TABLE. A hand-written scorecard
 * is a claim about the project made at one moment and never checked again;
 * the numbers in it decay silently and are then quoted as current. Every
 * value below is read from the artifact that owns it
 * (`scripts/scorecard-sources.mjs`), and `--check` — run by
 * `src/testing/docs-contract.test.ts` under `npm test` — fails the moment
 * the committed file stops matching its sources.
 *
 * WHY NOT A SINGLE SCORE. Soundness is not a scalar, and a 0-100 "quality
 * score" would average a gate that must never fail together with a
 * coverage figure that is expected to be partial (F7 § 23). The output is
 * a multidimensional table: what was measured, where it came from, what it
 * means, and — the column most easily dropped and most needed — what it
 * does NOT establish.
 */

import fs from "node:fs";
import path from "node:path";
import {
  ROOT,
  readFindingsRegister,
  readInvariantMap,
  readMeasurements,
  readOutputContract,
  readScripts,
  readSuiteShapes,
  readUncertaintyTaxonomy,
  readValidationCases,
} from "./scorecard-sources.mjs";

const OUTPUT = path.join(ROOT, "docs/SCORECARD.md");

const cell = (value) => String(value).replace(/\|/g, "\\|");
const row = (cells) => `| ${cells.map(cell).join(" | ")} |`;

/** `AFFECTED 5, NOT_AFFECTED 3` — a count map in declaration order. */
const counts = (map, order) =>
  (order ?? [...map.keys()])
    .filter((key) => map.has(key))
    .map((key) => `${key} ${map.get(key)}`)
    .join(", ");

async function build() {
  const invariants = await readInvariantMap();
  const taxonomy = await readUncertaintyTaxonomy();
  const suites = await readSuiteShapes();
  const validation = readValidationCases();
  const contract = readOutputContract();
  const register = readFindingsRegister();
  const scripts = readScripts();
  const measured = readMeasurements();

  const lines = [];
  const push = (...text) => lines.push(...text);

  push(
    "<!-- GENERATED by `node scripts/generate-scorecard.mjs`. Do not edit by hand. -->",
    "",
    "# VulnTrace Benchmark Scorecard",
    "",
    "The measured state of the project, generated from the artifacts that",
    "own each value. Regenerate with:",
    "",
    "```bash",
    "node scripts/generate-scorecard.mjs          # rewrite this file",
    "node scripts/generate-scorecard.mjs --check  # fail if it is stale",
    "```",
    "",
    "`--check` also runs inside `npm test`",
    "(`src/testing/docs-contract.test.ts`), so a source change that this",
    "file no longer reflects fails the suite rather than going unnoticed.",
    "",
    "**This is deliberately not a single score.** A soundness property that",
    "must never fail and a coverage figure that is expected to be partial",
    "cannot be averaged into one number without destroying both. Read the",
    "`Limitation` column: it is the part a summary would drop.",
    "",
    "## How to read the `Source` column",
    "",
    "| Kind | Meaning |",
    "| --- | --- |",
    "| **structural** | Derived from committed source with no test run, no clock and no network. `--check` proves it is current. |",
    "| **measured (deterministic)** | The recorded result of running a deterministic, offline command. `--check` proves this file matches the recording; it cannot prove the recording is fresh, so each row carries the commit and date it was taken at. |",
    "| **measured (LIVE)** | The recorded result of a command that queries the real OSV API over the network. Not reproducible byte-for-byte: advisory-database movement can change it without any change to this repository. |",
    "",
  );

  // -- 1. Deterministic Foundation gate --------------------------------
  push(
    "## 1. Deterministic Foundation gate",
    "",
    row(["Metric", "Current", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    row([
      "Foundation invariants with a named owner",
      invariants.count,
      "structural — `src/testing/foundation-invariants.ts`",
      "Every soundness property F1–F6 established has exactly one deterministic test that fails when it breaks.",
      "Membership only. The map proves an owner exists and is executed; it cannot prove the owner's assertions are semantically adequate.",
    ]),
    row([
      "Distinct owner test files",
      invariants.ownerFiles.length,
      "structural — the same map",
      "The invariants are spread across independent suites rather than concentrated in one fragile file.",
      "An owner may own more than one invariant; this is not a coverage percentage.",
    ]),
    row([
      "Test files the gate executes",
      suites.gateFileCount,
      "structural — `vitest.foundation.config.ts`",
      "`npm run test:foundation` is a subset of `npm test`, never a second suite.",
      "Gate files may contain assertions beyond the invariant they own.",
    ]),
    row([
      "Invariants by originating task",
      counts(invariants.byFoundation, [
        "F1",
        "F2",
        "F3",
        "F4",
        "F5",
        "F6",
        "VT-CONTRACT",
        "P1-A",
      ]),
      "structural — the same map",
      "Shows which Foundation task each guarantee came from.",
      "A task with fewer invariants did not necessarily do less work.",
    ]),
    row([
      "Gate result",
      `${measured.foundationGate.status} (${measured.foundationGate.tests} tests, ${measured.foundationGate.files} files)`,
      `measured (deterministic) — \`${measured.foundationGate.command}\` at \`${measured.foundationGate.commit}\`, ${measured.foundationGate.measuredAt}`,
      "The Foundation block's hard gate. It is offline and contains no network access at all.",
      "Green means no listed invariant broke — not that the analyzer is sound.",
    ]),
    "",
  );

  // -- 2. Suites -------------------------------------------------------
  push(
    "## 2. Test suites",
    "",
    row(["Suite", "Current", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    row([
      "`npm test` (full unit/integration/e2e)",
      `${measured.fullSuite.status} — ${measured.fullSuite.tests} tests, ${measured.fullSuite.files} files`,
      `measured (LIVE) — \`${measured.fullSuite.command}\` at \`${measured.fullSuite.commit}\`, ${measured.fullSuite.measuredAt}`,
      `${suites.unitTestFileCount} \`*.test.ts\` files exist under \`src/\`.`,
      "**Not fully offline.** `src/vulnerabilities/osv-provider.integration.test.ts` queries the live OSV API unconditionally, so this run is not a deterministic oracle. See `docs/OPEN-DEBTS.md`.",
    ]),
    row([
      "`npm run test:adversarial`",
      `${measured.adversarial.status} — ${measured.adversarial.tests} tests`,
      `measured (deterministic) — \`${measured.adversarial.command}\` at \`${measured.adversarial.commit}\`, ${measured.adversarial.measuredAt}`,
      "Two independent suites (v1, v2) built to detect overfitting.",
      "A research/coverage signal, not a contract owner: both suites deliberately keep scenarios that disagree with the analyzer rather than fixing the analyzer to pass them.",
    ]),
    row([
      "`npm run test:performance`",
      `${measured.performance.status} — ${measured.performance.tests} tests`,
      `measured (deterministic in shape, environmental in value) — \`${measured.performance.command}\` at \`${measured.performance.commit}\`, ${measured.performance.measuredAt}`,
      "Coarse catastrophic-regression smoke against generous wall-clock ceilings.",
      "Wall-clock, so machine-dependent. It answers 'did something explode', never 'is the complexity contract intact' — that is the structural operation-count gate `src/analysis/scan-caches.f5-multiplier.test.ts`.",
    ]),
    row([
      "`npm run test:validation`",
      measured.liveValidation.status,
      `measured (LIVE) — \`${measured.liveValidation.command}\` at \`${measured.liveValidation.commit}\`, ${measured.liveValidation.measuredAt}`,
      "Real npm-installed packages against real advisories over the real OSV API.",
      "Integration evidence and a provider-movement detector, never a correctness oracle. Owns no invariant in the map, on purpose.",
    ]),
    "",
  );

  // -- 3. Output contract ----------------------------------------------
  push(
    "## 3. Verdict and proof coverage",
    "",
    row(["Metric", "Current", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    row([
      "Verdicts in the serialized contract",
      `${contract.verdicts.length} — ${contract.verdicts.join(", ")}`,
      "structural — `schemas/result.schema.json`",
      "The closed vocabulary. There is no fourth verdict and no 'probably safe'.",
      "A closed vocabulary says nothing about how often each is reached.",
    ]),
    row([
      "Negative-proof families",
      `${contract.proofFamilies.length} — ${contract.proofFamilies.join(", ")}`,
      "structural — the schema's VT-CONTRACT-01 clause",
      "A `NOT_AFFECTED` carries exactly one, enforced at serialization, not merely in the analyzer.",
      "Exactly-one is a shape guarantee. That a family's own preconditions were honestly established is owned by F2/F4, not by the schema.",
    ]),
    row([
      "Top-level result properties",
      contract.topLevelProperties.map((name) => `\`${name}\``).join(", "),
      "structural — `schemas/result.schema.json`",
      "`unreportedCandidates` is a top-level array of its own, never merged into `findings`.",
      "Additive since F3: a result produced before those fields existed still validates, so a consumer cannot tell 'nothing was unreported' from 'this scan predates the field' by absence alone — which is why the producer always emits the array.",
    ]),
    row([
      "Finding properties",
      contract.findingProperties.map((name) => `\`${name}\``).join(", "),
      "structural — the same schema",
      "`unknownReasons` appears on an `UNKNOWN` and on nothing else; the negative proofs live under `evidence`.",
      "An `AFFECTED` and a `NOT_AFFECTED` carry no `unknownReasons` at all — asserted structurally, because attaching uncertainty to a finding that has a path or a proof invites a confidence question this analyzer does not answer.",
    ]),
    row([
      "F4 proof mutations applied",
      `${measured.proofMutation.total} (unsafe_survival ${measured.proofMutation.unsafeSurvival})`,
      `measured (deterministic) — \`${measured.proofMutation.command}\` at \`${measured.proofMutation.commit}\`, ${measured.proofMutation.measuredAt}`,
      "No mutation that removes a proof family's own prerequisite leaves that family standing.",
      "The mutation set is finite and hand-authored. `unsafe_survival === 0` is the gate; the other counts are informational lower bounds.",
    ]),
    row([
      "Verdict coverage in the offline differential",
      measured.differential.verdicts.join(", "),
      `measured (deterministic) — \`${measured.differential.command}\` at \`${measured.differential.commit}\`, ${measured.differential.measuredAt}`,
      "All three verdicts and all three proof families occur in a network-free corpus that proves its own non-vacuity.",
      "A small corpus chosen to be reasoned about, not a sample of real-world code.",
    ]),
    "",
  );

  // -- 4. PackageInstance identity -------------------------------------
  push(
    "## 4. PackageInstance identity controls",
    "",
    row(["Control", "Current", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    row([
      "Identity invariants with a named owner",
      [...invariants.invariants]
        .filter((invariant) => invariant.id.startsWith("package-instance"))
        .length,
      "structural — `src/testing/foundation-invariants.ts`",
      "Exactness of instance identity, and the binding of a proof to the instance it is about, are separately owned.",
      "Identity exactness does not imply the target resolved inside that instance is correct — that is P1-A's target-authority work.",
    ]),
    row([
      "Differential oracle against real Node",
      measured.instanceOracle.status,
      `measured (deterministic) — \`${measured.instanceOracle.command}\` at \`${measured.instanceOracle.commit}\`, ${measured.instanceOracle.measuredAt}`,
      "Twins, npm aliases, scoped collisions, symlink convergence and workspace identity are compared against what real Node actually loads.",
      "Covers the enumerated shapes only; an install layout nobody wrote a case for is not covered.",
    ]),
    "",
  );

  // -- 5. Uncertainty ---------------------------------------------------
  push(
    "## 5. Uncertainty taxonomy",
    "",
    row(["Metric", "Current", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    row([
      "Categories",
      `${taxonomy.categories.length} — ${taxonomy.categories.join(", ")}`,
      "structural — `src/domain/uncertainty.ts`",
      "Each category names a different KIND of work, which is the only property that makes a taxonomy worth having.",
      "**Observational.** Nothing in the taxonomy authorizes a proof or is read by any branch that decides a verdict.",
    ]),
    row([
      "Specific reasons classified",
      taxonomy.reasons.length,
      "structural — the same file, exhaustiveness compile-enforced",
      "Every `DynamicCallReason` appears verbatim and every reason has exactly one category.",
      "Eight of them are the P1-B1 frontend-gap subtypes; `unsupported_construct` survives as their runtime floor, not as a bucket — see §7.1.",
    ]),
    "",
    "Reasons per category:",
    "",
    row(["Category", "Reasons"]),
    row(["---", "---"]),
    ...[...taxonomy.byCategory.entries()].map(([category, reasons]) =>
      row([`\`${category}\``, reasons.length]),
    ),
    "",
  );

  // -- 6. Real-world benchmark ------------------------------------------
  push(
    "## 6. Real-world benchmark",
    "",
    row(["Metric", "Current", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    row([
      "Cases",
      validation.total,
      "structural — `tests/validation/cases/cases.json`",
      "Real, npm-installed packages against real advisories; oracles authored from the advisory and the real source, independently of VulnTrace's output.",
      "17 cases is a shape corpus, not a statistical sample. No precision/recall figure is claimed from it.",
    ]),
    row([
      "Expected-verdict distribution",
      counts(validation.byExpected, ["AFFECTED", "NOT_AFFECTED", "UNKNOWN"]),
      "structural — the same file",
      "The corpus is deliberately balanced so that 'vulnerable version installed' and 'vulnerable behavior reachable' can disagree.",
      "These are the ORACLES, not the results.",
    ]),
    row([
      "Known failures (kept failing on purpose)",
      `${validation.knownFailures.length} — ${validation.knownFailures.map((testCase) => testCase.id).join(", ")}`,
      "structural — `knownFailure: true` in the same file",
      "A disagreement with an independently-researched oracle is recorded and kept red, never silently fixed away or re-scoped to match the tool.",
      "One of them (`RWB-09b`) is a benchmark ORACLE-DESIGN limitation, not an analyzer defect: the correct result is no finding at all, which the case format cannot express.",
    ]),
    row([
      "Last recorded live run",
      `${measured.liveValidation.passed} passed / ${measured.liveValidation.failed} failed (${measured.liveValidation.knownFailures} known, ${measured.liveValidation.unexpected} unexpected)`,
      `measured (LIVE) — \`${measured.liveValidation.command}\`, ${measured.liveValidation.measuredAt}`,
      "Historical measurement, reproduced in `tests/validation/REPORT.md`.",
      "Live. A rerun today can differ because the advisory database moved, not because this repository changed.",
    ]),
    "",
  );

  // -- 7. Uncertainty pressure, by remediation domain --------------------
  push(
    "## 7. Where the UNKNOWN pressure actually is",
    "",
    "Reporting metadata only. **This is a second, orthogonal dimension on",
    "top of the six categories in §5 — it is not a seventh category**, it",
    "appears in no output, and no proof rule reads it.",
    "",
    row(["Remediation domain", "Occurrences", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    ...measured.uncertaintyDistribution.byDomain.map((entry) =>
      row([
        entry.domain,
        entry.occurrences,
        // Same provenance shape as every other measured row: command,
        // commit and date. This is the OLDEST measurement in the file —
        // taken at a different commit from the gate runs — so omitting
        // its commit here would leave the one value most likely to be
        // stale as the one whose provenance was hardest to check.
        `measured (LIVE) — \`${measured.uncertaintyDistribution.command}\` at \`${measured.uncertaintyDistribution.commit}\`, ${measured.uncertaintyDistribution.measuredAt}`,
        entry.interpretation,
        entry.limitation,
      ]),
    ),
    "",
    "The single most misread row is **target intelligence**:",
    `\`no_vulnerable_symbol_rule\` accounts for ${measured.uncertaintyDistribution.targetIntelligenceOccurrences} of the`,
    "corpus's occurrences and is a **corpus/config artifact**, not evidence",
    "the JavaScript frontend could not understand the code. Each fixture",
    "configures exactly one rule — the advisory under test — so every other",
    "advisory the live OSV API returns for the same installed packages",
    "produces an UNKNOWN meaning *'this benchmark has no rule for that",
    "advisory'*. Counting it as a frontend failure would put permanent",
    "non-work at the top of the roadmap.",
    "",
    "Excluding it, the corpus's analyzer-attributable uncertainty is",
    `**${measured.uncertaintyDistribution.analyzerAttributableFindings} UNKNOWN findings**, and the blockers behind the largest of`,
    "them contain **zero capability escapes** — nothing that can load or",
    "execute code the graph never discovered. That is a materially",
    "different conclusion from \"real code contains `eval`, so UNKNOWN is",
    "inevitable\", and it is why P1-B is worth doing at all.",
    "",
    "**Occurrence counts are not work estimates.** They measure the SHAPE",
    "of the uncertainty, not the cost of removing it: occurrences collapse",
    "into a handful of distinct reasons, one change can discharge many at",
    "once, and target-relevant completeness may discharge most of them",
    "without modeling a single construct. See `docs/OPEN-DEBTS.md` D-06.",
    "",
  );

  // -- 7.1 The frontend row, decomposed (P1-B1/P1-B2) ---------------------
  const gaps = measured.frontendGapDistribution;

  // RECONCILIATION, ASSERTED RATHER THAN CLAIMED. The whole value of a
  // decomposition is that it accounts for exactly what it replaced, so the
  // two ways of saying it must agree or the scorecard must not be written
  // at all. Checked here rather than trusted because these are MEASURED
  // values a human transcribes from a command's output (F7's own
  // structural/measured split), and a transcription slip that left the
  // totals disagreeing is precisely the failure this section exists to
  // rule out.
  const subtypeOccurrences = gaps.bySubtype.reduce(
    (total, entry) => total + entry.occurrences,
    0,
  );
  const subtypeBlocking = gaps.bySubtype.reduce(
    (total, entry) => total + entry.blocking,
    0,
  );
  const frontendDomain = measured.uncertaintyDistribution.byDomain.find(
    (entry) => entry.domain === "frontend",
  );
  if (subtypeOccurrences !== gaps.graphWideOccurrences) {
    throw new Error(
      `measurements.json: frontendGapDistribution subtypes sum to ` +
        `${subtypeOccurrences} graph-wide occurrences, but graphWideOccurrences ` +
        `is ${gaps.graphWideOccurrences}.`,
    );
  }
  if (subtypeBlocking !== gaps.blockingOccurrences) {
    throw new Error(
      `measurements.json: frontendGapDistribution subtypes sum to ` +
        `${subtypeBlocking} blocking occurrences, but blockingOccurrences is ` +
        `${gaps.blockingOccurrences}.`,
    );
  }
  if (!frontendDomain || frontendDomain.occurrences !== subtypeBlocking) {
    throw new Error(
      `measurements.json: §7's frontend row reports ` +
        `${frontendDomain ? frontendDomain.occurrences : "no"} occurrences, but ` +
        `§7.1's subtypes account for ${subtypeBlocking}. The decomposition must ` +
        "account for exactly what it replaced.",
    );
  }

  push(
    "### 7.1 Which frontend gap, specifically",
    "",
    "The `frontend` row above used to be one opaque token. It is now eight",
    "measured gaps plus a retained floor (P1-B1; `tests/validation/FINDINGS.md` RWF-041).",
    "**This did not improve coverage** — the analyzer models exactly what it",
    "modelled before, and the corpus's UNKNOWN count is unchanged. It",
    "improved OBSERVABILITY: the question 'which capability should P1-B",
    "build first?' now has evidence behind it instead of intuition.",
    "",
    "**Two counts, and confusing them is the whole trap.** *Graph-wide* is",
    "every unresolved edge anywhere the graph builder walked, across all 17",
    "projects — the shape of real JavaScript, not a work queue. *Blocking*",
    "is the subset a search for a real vulnerable target actually traversed",
    "— the occurrences that cost a verdict. They rank the subtypes",
    "differently, and that disagreement is the most useful thing here.",
    "",
    row([
      "Frontend gap",
      "Graph-wide",
      "Blocking",
      "Projects",
      "Packages",
      "Sites",
      "Likely domain",
      "Example shape",
    ]),
    row(["---", "---", "---", "---", "---", "---", "---", "---"]),
    ...gaps.bySubtype.map((entry) =>
      row([
        `\`${entry.reason}\``,
        entry.occurrences,
        entry.blocking,
        entry.distinctFixtures,
        entry.distinctPackages,
        entry.distinctSites,
        entry.domain,
        entry.example,
      ]),
    ),
    "",
    `Totals: **${gaps.graphWideOccurrences} graph-wide**, **${gaps.blockingOccurrences} blocking**,`,
    `**${gaps.genericFallbackOccurrences} on the generic floor**. The blocking column reconciles`,
    "exactly with the `frontend` row in §7 — the decomposition moved no",
    "count, it only named them.",
    "",
    `**Sample-size warning.** All ${gaps.blockingOccurrences} blocking occurrences come from`,
    `**${gaps.blockingCases} case** (RWB-05), and they collapse into 19 distinct call`,
    "sites in 13 functions, not 42 independent gaps. They are also the",
    "same occurrences RWF-002 is about: they sit in `qs`'s *stringify*",
    "path while the vulnerable target is in its *parse* path, so",
    "reachability scoping might discharge every one of them without",
    "modeling a single construct. Do not read this column as a work plan",
    "on its own.",
    "",
    "Provenance for both columns: measured (LIVE) — " +
      `\`${gaps.command}\` at \`${gaps.commit}\`, ${gaps.measuredAt}.`,
    "",
  );

  // -- 8. Known defect register ------------------------------------------
  push(
    "## 8. Known defect register (RWF)",
    "",
    row(["Metric", "Current", "Source", "Interpretation", "Limitation"]),
    row(["---", "---", "---", "---", "---"]),
    row([
      "Findings recorded",
      register.rows.length,
      "structural — the status table in `tests/validation/FINDINGS.md`",
      "Every gap found by scanning real packages is recorded before it is fixed, and stays recorded after.",
      "Counts rows in the register, not distinct defects in the analyzer.",
    ]),
    row([
      "Still open",
      `${register.open.length} — ${register.open.map((entry) => entry.id).join(", ")}`,
      "structural — the same table",
      "Each is a precision gap that degrades to UNKNOWN in both directions, never a false verdict.",
      "'Open' is a status word in a table, not a scheduled task. See `docs/OPEN-DEBTS.md`.",
    ]),
    row([
      "Open in part",
      `${register.partlyOpen.length} — ${register.partlyOpen.map((entry) => entry.id).join(", ")}`,
      "structural — the same table",
      "Partly discharged, partly outstanding. RWF-002 is bypassed for unloaded packages; its underlying reachability-scoping tradeoff remains.",
      "**Counting these as closed is the register's single most consequential misreading**, and the blocker counts recorded for RWF-002 are not an implementation task count. See `docs/OPEN-DEBTS.md` D-06.",
    ]),
    row([
      "Recorded as fixed",
      register.fixed.length,
      "structural — the same table",
      "Every soundness defect found so far has a fixture and a test that keeps it fixed.",
      "A fix is proven for the shapes its fixtures cover.",
    ]),
    "",
  );

  // -- 9. Commands -------------------------------------------------------
  push(
    "## 9. Commands referenced by the documentation",
    "",
    "Every command below exists in `package.json`. Nothing aspirational is",
    "documented; `src/testing/docs-contract.test.ts` fails if a documented",
    "`npm run` target stops existing.",
    "",
    "The `Network?` column is derived from what each script actually runs,",
    "not from a remembered list: the one live suite inside the default",
    "vitest run is `src/vulnerabilities/osv-provider.integration.test.ts`,",
    "so every invocation that neither excludes the integration tests nor",
    "points at an offline config reaches OSV.",
    "",
    row(["Script", "Deterministic?", "Network?"]),
    row(["---", "---", "---"]),
    ...scripts.map((script) =>
      row([
        `\`npm run ${script.name}\``,
        script.deterministic
          ? "yes"
          : script.why === undefined
            ? "no"
            : `no — ${script.why}`,
        script.network ? "**yes — live OSV**" : "no",
      ]),
    ),
    "",
  );

  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`;
}

const generated = await build();

if (process.argv.includes("--check")) {
  const committed = fs.existsSync(OUTPUT)
    ? fs.readFileSync(OUTPUT, "utf-8")
    : "";
  if (committed !== generated) {
    process.stderr.write(
      "docs/SCORECARD.md is stale: it no longer matches its sources.\n" +
        "Regenerate it with `node scripts/generate-scorecard.mjs`.\n",
    );
    process.exit(1);
  }
  process.stdout.write("docs/SCORECARD.md is current.\n");
} else {
  fs.writeFileSync(OUTPUT, generated);
  process.stdout.write(`wrote ${path.relative(ROOT, OUTPUT)}\n`);
}
